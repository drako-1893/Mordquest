const assert = require('node:assert/strict');
const { test } = require('node:test');

test('Colocar, mover, anotar, marcar, borrar y deshacer funcionan sin DOM', async () => {
  const { BoardHistory, BoardState } = await import('../web/static/js/game/board-state.js');
  const board = new BoardState(6);
  const history = new BoardHistory();
  board.place('A', 0);
  assert.equal(board.occupantAt(0), 'A');
  assert.equal(board.crossAt(1), 'automática');
  history.record(board);
  board.place('A', 7);
  board.setNote(14, 'B', true);
  board.setNote(14, 'C', true);
  board.setCross(15, true);
  assert.equal(board.occupantAt(0), undefined);
  assert.equal(board.occupantAt(7), 'A');
  assert.deepEqual([...board.notes.get(14)], ['B', 'C']);
  assert.equal(board.crossAt(15), 'manual');
  board.setCross(8, false);
  assert.equal(board.crossAt(8), '');
  board.erase(14);
  board.erase(7);
  assert.equal(board.canErase(14), false);
  assert.equal(board.hiddenCrosses.has(8), false);
  const restored = history.undo();
  assert.equal(restored.occupantAt(0), 'A');
  assert.equal(restored.crossAt(15), '');
  assert.equal(history.length, 0);
});
